import 'package:equatable/equatable.dart';

import '../../prayer_times/domain/entities/prayer_times.dart';

/// The backend defines `on_time`, `late` and `missed`, but only `on_time` is
/// ever written today. Anything else maps to [unknown] instead of failing.
enum PrayerLogStatus {
  onTime,
  late,
  missed,
  unknown;

  static PrayerLogStatus parse(String? raw) => switch (raw) {
    'on_time' => onTime,
    'late' => late,
    'missed' => missed,
    _ => unknown,
  };
}

/// What a viewer sees of someone's snap on a prayer log. A snap can be opened
/// once per person and expires for everyone when the prayer window ends.
enum SnapState {
  /// No snap was sent to this group (only the prayer is shown).
  none,

  /// A snap the viewer has not opened yet: "tap to view".
  unopened,

  /// The viewer already opened it: no image, no tap.
  opened,

  /// The prayer window ended: closed for everyone.
  expired,
}

/// A snap opened for viewing: the link works once and must not be kept.
class OpenedSnap {
  final String url;

  /// The sender's chosen view time, when the server repeats it.
  final int? viewDurationSeconds;
  const OpenedSnap({required this.url, this.viewDurationSeconds});
}

/// One logged prayer. [date] is the prayer-day date (`yyyy-MM-dd`, in the
/// user's profile timezone) — an Isha logged at 12:30 AM keeps the previous
/// day's date — so it is kept as the server's string, not a [DateTime].
class PrayerLog extends Equatable {
  final String id;
  final PrayerName prayer;
  final String date;
  final PrayerLogStatus status;
  final int points;

  /// Signed Cloudinary URL, regenerated by the server on every read; null if
  /// there is no photo. Don't persist it.
  ///
  /// On other members' logs this is always null: their snap is opened through
  /// `POST /prayers/logs/{id}/view` instead. On your own log it is set only
  /// while the window is open.
  final String? snapUrl;

  /// A snap was sent to this group and the viewer has not opened it.
  final bool hasSnap;

  /// The viewer has opened this snap (a snap opens once per person).
  final bool snapViewed;

  /// The window ended: the snap is gone for everyone, the sender included.
  final bool snapExpired;

  /// Whether [windowEndsAt] is the server's. A live event carries no window,
  /// so its logs are not judged expired by the clock.
  final bool windowKnown;
  final DateTime windowStartsAt;
  final DateTime windowEndsAt;
  final DateTime loggedAt;

  /// Seconds the snap stays on screen for viewers (1 to 10), as the sender
  /// chose. Null when the server did not send it.
  final int? viewDurationSeconds;

  /// How long a viewer sees the snap: the sender's choice, or [fallback].
  Duration viewDuration([Duration fallback = const Duration(seconds: 6)]) =>
      viewDurationSeconds == null
      ? fallback
      : Duration(seconds: viewDurationSeconds!);

  const PrayerLog({
    required this.id,
    required this.prayer,
    required this.date,
    required this.status,
    required this.points,
    required this.snapUrl,
    required this.windowStartsAt,
    required this.windowEndsAt,
    required this.loggedAt,
    this.viewDurationSeconds,
    this.hasSnap = false,
    this.snapViewed = false,
    this.snapExpired = false,
    this.windowKnown = true,
  });

  /// How the snap shows to the viewer at [now]. The clock is checked as well
  /// as the server's flag, so a tile greys out the moment the window ends
  /// instead of at the next fetch.
  SnapState snapState(DateTime now) {
    if (snapExpired) return SnapState.expired;
    if (!hasSnap && !snapViewed && snapUrl == null) return SnapState.none;
    if (windowKnown && !now.isBefore(windowEndsAt)) return SnapState.expired;
    return snapViewed ? SnapState.opened : SnapState.unopened;
  }

  /// This log with the snap marked opened (the viewer just closed it).
  PrayerLog asViewed() => _withSnap(viewed: true);

  /// This log with the snap marked expired (the server said the window ended).
  PrayerLog asExpired() => _withSnap(expired: true);

  PrayerLog _withSnap({bool viewed = false, bool expired = false}) => PrayerLog(
    id: id,
    prayer: prayer,
    date: date,
    status: status,
    points: points,
    snapUrl: snapUrl,
    windowStartsAt: windowStartsAt,
    windowEndsAt: windowEndsAt,
    loggedAt: loggedAt,
    viewDurationSeconds: viewDurationSeconds,
    hasSnap: false,
    snapViewed: viewed || snapViewed,
    snapExpired: expired || snapExpired,
    windowKnown: windowKnown,
  );

  /// Undo is allowed only while the window is still open.
  bool canUndo(DateTime now) => now.isBefore(windowEndsAt);

  @override
  List<Object?> get props => [
    id,
    prayer,
    date,
    status,
    points,
    snapUrl,
    hasSnap,
    snapViewed,
    snapExpired,
    windowKnown,
    windowStartsAt,
    windowEndsAt,
    loggedAt,
    viewDurationSeconds,
  ];
}

/// Logs keyed by prayer-day date, each day ordered Fajr → Isha.
Map<String, List<PrayerLog>> groupLogsByDate(Iterable<PrayerLog> logs) {
  final byDate = <String, List<PrayerLog>>{};
  for (final log in logs) {
    byDate.putIfAbsent(log.date, () => []).add(log);
  }
  for (final day in byDate.values) {
    day.sort((a, b) => a.prayer.index.compareTo(b.prayer.index));
  }
  return byDate;
}
